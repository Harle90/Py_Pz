#Вар. 8 Дан размер файла в байтах. Используя операцию деления нацело,найти количество полных килобайтов, которые занимает данный файл (1 килобайт = 1024байта).
try:
    #Ввод размера файла в байтах
    byte = int(input("Введите размер файла"))
    #Деление нацело веденного числа
    kb = byte // 1024
    #Вывод кол-ва кб
    print(f"Полный размер в кб: {kb}")
    #Обработка ошибки при нечисловом значении
except ValueError:
    print("Ошибка")
